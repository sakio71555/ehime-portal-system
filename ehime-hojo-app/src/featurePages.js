function renderFeatureList(items = []) {
  return items.map((item) => `<li>${item}</li>`).join('');
}

function renderFeatureLinks(links = []) {
  return links.map((link) => `<a href="${link.href}">${link.label}</a>`).join('');
}

function renderFeatureRows(rows = []) {
  return rows
    .map(
      (row) => `
          <tr>
            <td>${row.theme}</td>
            <td>${row.useCase}</td>
            <td>${row.point}</td>
          </tr>`
    )
    .join('');
}

