export function getFeatureKeywords(feature) {
  return [
    ...(feature.targetKeywords || []),
    ...(feature.purposeTags || []),
    ...(feature.industryTags || []),
    ...(feature.searchKeywords || []),
  ].filter(Boolean);
}

export function getTopFeaturePages(limit = 6) {
  return [...FEATURE_PAGES].sort((a, b) => b.priority - a.priority).slice(0, limit);
}
